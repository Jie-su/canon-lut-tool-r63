#!/usr/bin/env python3
"""Fail closed on private camera/user artifacts and credentials in public output."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
PRIVATE_SUFFIXES = {'.pf3', '.pf2', '.bin', '.cube', '.cr3', '.cr2', '.crw', '.jpg', '.jpeg', '.log', '.dmg', '.pkg', '.zip'}
IMAGE_ALLOW = {'app/assets/AppIcon.png', 'app/assets/AppIcon.icns', 'docs/images/workspace.png'}
MACHO = {b'\xcf\xfa\xed\xfe', b'\xfe\xed\xfa\xcf', b'\xca\xfe\xba\xbe', b'\xbe\xba\xfe\xca'}
TOKENS = re.compile(rb'(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----)')
PERSONAL = re.compile((r'/' + r'Users/[^\s"\x00]+').encode())


def source_files():
    if (ROOT / '.git').exists():
        result = subprocess.check_output(['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z'], cwd=ROOT)
        return sorted({ROOT / name.decode() for name in result.split(b'\0') if name})
    excluded = {'.git', 'dist', 'build', '__pycache__', '.venv'}
    return sorted(p for p in ROOT.rglob('*') if p.is_file() and not any(part in excluded for part in p.relative_to(ROOT).parts))


def audit_source():
    errors = []
    paths = source_files()
    for path in paths:
        rel = path.relative_to(ROOT).as_posix()
        if not path.is_file() or path.is_symlink():
            errors.append(f'{rel}: missing, unsupported, or symlink')
            continue
        raw = path.read_bytes()
        if path.suffix.lower() in PRIVATE_SUFFIXES:
            errors.append(f'{rel}: camera/user/binary archive format is not public source')
        if 'resources' in path.relative_to(ROOT).parts or rel.startswith('local/'):
            errors.append(f'{rel}: private resource directory')
        if raw[:4] in MACHO:
            errors.append(f'{rel}: compiled executable in source tree')
        if path.suffix.lower() in {'.png', '.icns'} and rel not in IMAGE_ALLOW:
            errors.append(f'{rel}: image has not been approved as an original public asset')
        if len(raw) > 250_000 and rel not in IMAGE_ALLOW:
            errors.append(f'{rel}: unexpectedly large source file')
        if TOKENS.search(raw):
            errors.append(f'{rel}: credential/key pattern')
        if PERSONAL.search(raw):
            errors.append(f'{rel}: personal absolute home path')
    return paths, errors


def audit_bundle(app):
    errors = []
    files = [p for p in app.rglob('*') if p.is_file()]
    allowed_helpers = {'CanonLUTTool', 'eds_r6_tool', 'native_pf3_preview'}
    for path in files:
        rel = path.relative_to(app).as_posix()
        raw = path.read_bytes()
        if path.suffix == '.pyc' or '__pycache__' in path.parts:
            errors.append(f'{rel}: generated bytecode/build paths must not be shipped')
        if path.suffix.lower() in PRIVATE_SUFFIXES:
            errors.append(f'{rel}: private/camera data must not be shipped')
        if any(name in rel for name in ['EDSDK.framework', 'EdsCFParse.bundle', 'DppCore.bundle', 'MLib.bundle']):
            errors.append(f'{rel}: proprietary Canon component must be installed by user')
        if 'backend/r6lut/resources' in rel or 'snapshot' in path.name.lower():
            errors.append(f'{rel}: private context or camera snapshot')
        if raw[:4] in MACHO and not (rel.startswith('Contents/Resources/python/') or (path.parent.name == 'MacOS' and path.name in allowed_helpers)):
            errors.append(f'{rel}: unexpected executable')
        # The upstream interpreter may have its own build-path strings. Audit
        # our executables/backend/docs independently of that third-party binary.
        if not rel.startswith('Contents/Resources/python/'):
            if TOKENS.search(raw) or PERSONAL.search(raw):
                errors.append(f'{rel}: credential or personal absolute path')
    for expected in ['Contents/Resources/LICENSE', 'Contents/Resources/THIRD_PARTY_NOTICES.md', 'Contents/Resources/licenses/SOURCES.json']:
        if not (app / expected).is_file():
            errors.append(f'{expected}: missing distribution notice')
    return files, errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', type=Path)
    args = parser.parse_args()
    paths, errors = audit_bundle(args.bundle.resolve()) if args.bundle else audit_source()
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    print(json.dumps({'status': 'passed', 'kind': 'bundle' if args.bundle else 'source', 'filesChecked': len(paths)}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
